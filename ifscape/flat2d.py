"""2D "Live Floor Plan" set, sibling of blender.py: reads the 'flat' field of each scene and writes
clips/<slug>/<id>.mp4 (1080x1920, 30 fps, bt709), the same contract as Blender, so the render does not change.

The duration of each scene is the same as Blender's (blender.timeline: voice = voice.json + slack; text = seconds
of the scene). Frames go from Pillow straight to FFmpeg through stdin (no PNG on disk). It also writes
build/<slug>/flat2d/timeline.json with the frame of each event, for the sound design.
Drawing code in tools/flat2d/.
"""

import json
import subprocess
import sys
import time
from pathlib import Path

from . import blender, brand
from .script import Script
from .util import ROOT, build_dir, clips_dir

MARKER = ".flat2d"           # clips in the folder came from here (may be overwritten, like Blender's)
ENCODE = ["-c:v", "libx264", "-preset", "medium", "-crf", "14", "-pix_fmt", "yuv420p",
          "-color_primaries", "bt709", "-color_trc", "bt709", "-colorspace", "bt709"]


def _engine():
    tools = str(ROOT / "tools")
    if tools not in sys.path:
        sys.path.insert(0, tools)
    from flat2d import engine
    return engine


def uses_flat(script: Script) -> bool:
    return any(s.flat for s in script.scenes)


def _minutes(hhmm: str) -> int:
    h, m = hhmm.split(":")
    return int(h) * 60 + int(m)


def hud_specs(script: Script) -> dict[str, dict]:
    """HUD of each scene: the clock continues from the previous scene (stopped at the last time) until another scene changes it;
    'clock': null hides it. Chips only apply to their own scene."""
    out, carried = {}, None
    for s in script.scenes:
        if s.clock is not None:
            if s.clock is False:
                carried = None
            else:
                a = _minutes(s.clock["from"])
                b = _minutes(s.clock.get("to", s.clock["from"]))
                carried = (int(s.clock.get("day", 0)), a, b if b >= a else b + 24 * 60)
        spec = {"clock": carried, "chips": list(s.chip)}
        out[s.id] = spec
        if carried:
            carried = (carried[0], carried[2], carried[2])
    return out


def _check_clip_dir(slug: str, force: bool) -> Path:
    d = clips_dir(slug)
    d.mkdir(parents=True, exist_ok=True)
    foreign = [p.name for p in d.glob("*.mp4")]
    if foreign and not ((d / MARKER).exists() or (d / blender.MARKER).exists()) and not force:
        raise SystemExit(f"clips/{slug}/ already has clips that came neither from flat2d nor from Blender "
                         f"({', '.join(foreign[:4])}…). Use --force to replace them.")
    (d / MARKER).write_text("clips generated by 'py -m ifscape flat2d'\n", encoding="utf-8")
    return d


def _clips(script: Script, manifest: dict | None, tl: dict) -> dict:
    engine = _engine()
    huds = hud_specs(script)
    by_id = {s.id: s for s in script.scenes}
    clips = {}
    for row in tl["scenes"]:
        sc = by_id[row["id"]]
        if not sc.flat:
            continue
        words = (manifest or {}).get(sc.id, {}).get("words")
        clip = engine.Clip(sc.flat, (row["end"] - row["start"]) / brand.FPS, sc.narration, words, huds[sc.id],
                           script.cast)
        clips[sc.id] = clip
    return clips


def _write_timeline(script: Script, tl: dict, clips: dict, out: Path) -> Path:
    scenes = []
    for row in tl["scenes"]:
        clip = clips.get(row["id"])
        sc = {k: row[k] for k in ("id", "start", "end", "seconds")}
        if clip:
            flat = next(s.flat for s in script.scenes if s.id == row["id"])
            sc.update(shot=flat["shot"], place=flat.get("place") or flat.get("set"),
                      events=[{**c, "frame": row["start"] + c["frame"], "scene_frame": c["frame"],
                               **({"out_frame": row["start"] + c["out_frame"]} if "out_frame" in c else {})}
                              for c in clip.cues()])
        scenes.append(sc)
    path = out / "timeline.json"
    path.write_text(json.dumps({"fps": brand.FPS, "frames": tl["frames"], "estimated": tl["estimated"],
                                "scenes": scenes}, indent=2, ensure_ascii=False), encoding="utf-8")
    return path


def _encode(clip, out: Path) -> None:
    proc = subprocess.Popen(["ffmpeg", "-y", "-v", "error", "-f", "rawvideo", "-pix_fmt", "rgb24",
                             "-s", f"{brand.W}x{brand.H}", "-r", str(brand.FPS), "-i", "-", *ENCODE,
                             "-r", str(brand.FPS), str(out)], stdin=subprocess.PIPE, stderr=subprocess.PIPE)
    try:
        for i in range(clip.frames):
            proc.stdin.write(clip.frame(i).tobytes())
    finally:
        proc.stdin.close()
        err = proc.stderr.read().decode(errors="ignore")
        proc.wait()
    if proc.returncode:
        raise RuntimeError(f"FFmpeg falhou no clipe {out.name}:\n{err[-800:]}")


def render(script: Script, manifest: dict | None, stills: str | None = None, force: bool = False) -> Path:
    """stills='30,900': only those frames (numbering of the whole video, starting at 1, as in Blender) as PNG,
    for review; without it, all the clips of the scenes with 'flat'."""
    if not uses_flat(script):
        raise SystemExit("No scene has 'flat': nothing for the 2D set to draw.")
    out = build_dir(script.slug) / "flat2d"
    out.mkdir(exist_ok=True)
    tl = blender.timeline(script, manifest or None)
    clips = _clips(script, manifest, tl)
    tl_path = _write_timeline(script, tl, clips, out)
    note = " (estimated: narration not generated yet)" if tl["estimated"] else ""
    print(f"  timeline: {tl['frames']} frames, {tl['frames'] / brand.FPS:.1f} s{note} -> "
          f"{tl_path.relative_to(ROOT)}")
    t0, done = time.monotonic(), 0
    if stills:
        for n in (int(v) for v in stills.split(",") if v.strip()):
            row = next((r for r in tl["scenes"] if r["start"] < n <= r["end"]), None)
            if not row or row["id"] not in clips:
                print(f"  frame {n}: outside the 'flat' scenes")
                continue
            path = out / f"still_{n:04d}.png"
            clips[row["id"]].frame(n - 1 - row["start"]).save(path)
            done += 1
            print(f"  {path.relative_to(ROOT)} (scene {row['id']})")
    else:
        clip_dir = _check_clip_dir(script.slug, force)
        for sid, clip in clips.items():
            path = clip_dir / f"{sid}.mp4"
            _encode(clip, path)
            done += clip.frames
            print(f"  {path.relative_to(ROOT)}  ({clip.frames} frames)")
    secs = time.monotonic() - t0
    rate = secs / done if done else 0.0
    with (out / "render_log.jsonl").open("a", encoding="utf-8") as f:
        f.write(json.dumps({"when": time.strftime("%Y-%m-%d %H:%M"), "mode": "stills" if stills else "anim",
                            "frames": done, "seconds": round(secs, 1), "s_per_frame": round(rate, 3)}) + "\n")
    print(f"  flat2d: {secs:.1f} s ({done} frames, {rate:.3f} s/frame)")
    return out
