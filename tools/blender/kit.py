def reset_scene(frames: int, fps: int):
    bpy.ops.wm.read_factory_settings(use_empty=True)
    scene = bpy.context.scene
    scene.render.engine = "BLENDER_EEVEE"
    scene.render.resolution_x, scene.render.resolution_y = 1080, 1920
    scene.render.fps = fps
    scene.frame_start, scene.frame_end = 1, frames
    scene.eevee.taa_render_samples = 32
    # Virtual shadow map pool: the default (512 MB = 2048 pages) overflows in open scenes ("Shadow buffer full")
    # and the shadow flickers frame to frame even with a still camera (two-humans-left, 40-53 s, 2026-10-22).
    # 1024 MB = 4096 pages (measured: peak 3420 in the videos already made).
    scene.eevee.shadow_pool_size = "1024"
    # Standard, not AgX: with AgX the brand amber came out dull and orange turned
    # salmon (docs/blender/effects-and-lighting.md). Sun and ambient were tuned for AgX: review them.
    scene.view_settings.view_transform = "Standard"
    scene.view_settings.look = "None"
    add_look_post(scene)
    if os.environ.get("IFSCAPE_PREVIEW"):            # animation preview for animation-qa: half resolution
        scene.render.resolution_percentage = 50
        scene.eevee.taa_render_samples = 16
    return scene


def add_look_post(scene, bloom=True, vignette=0.22):
    """Channel compositor (docs/art-bible.md section 5): Glare Bloom (threshold 1.0,
    smoothness 0.3, strength 0.25, size 0.5: only what exceeds 1.0 emission glows; threshold 0.85 blew out the moonlight
    path) and vignette (ellipse 1.15 x 1.0, 300 px blur, 22% darkening at the corners). Measured cost: +0.03 s/frame."""
    ng = bpy.data.node_groups.new("Look", "CompositorNodeTree")
    ng.interface.new_socket("Image", in_out="OUTPUT", socket_type="NodeSocketColor")
    N, L = ng.nodes, ng.links
    rl, outn = N.new("CompositorNodeRLayers"), N.new("NodeGroupOutput")
    cur = rl.outputs["Image"]
    if bloom:
        g = N.new("CompositorNodeGlare")
        g.inputs["Type"].default_value = "Bloom"
        g.inputs["Quality"].default_value = "High"
        g.inputs["Threshold"].default_value = 1.0
        g.inputs["Smoothness"].default_value = 0.3
        g.inputs["Strength"].default_value = 0.25
        g.inputs["Size"].default_value = 0.5
        L.new(cur, g.inputs["Image"])
        cur = g.outputs[0]
    if vignette:
        m = N.new("CompositorNodeEllipseMask")
        m.inputs["Size"].default_value = (1.15, 1.0)
        b = N.new("CompositorNodeBlur")
        b.inputs["Size"].default_value = (300, 300)
        L.new(m.outputs[0], b.inputs["Image"])
        dark = N.new("ShaderNodeMix")
        dark.data_type, dark.blend_type = "RGBA", "MULTIPLY"
        dark.inputs[0].default_value = vignette
        L.new(cur, dark.inputs[6])
        dark.inputs[7].default_value = (0, 0, 0, 1)
        mix = N.new("ShaderNodeMix")
        mix.data_type = "RGBA"
        L.new(b.outputs[0], mix.inputs[0])
        L.new(dark.outputs[2], mix.inputs[6])
        L.new(cur, mix.inputs[7])
        cur = mix.outputs[2]
    L.new(cur, outn.inputs[0])
    scene.compositing_node_group = ng
    scene.render.use_compositing = True


def run(build):
    """Reads --timeline/--out/--stills/--anim, builds the scene with build(timeline) and renders."""
    args = sys.argv[sys.argv.index("--") + 1:] if "--" in sys.argv else []

    def opt(name):
        return args[args.index(name) + 1] if name in args else None

    tl = Timeline(json.loads(Path(opt("--timeline")).read_text(encoding="utf-8")))
    out = Path(opt("--out"))
    if not out.is_absolute():
        raise SystemExit(f"--out must be an absolute path with a drive (got '{out}'): a relative path writes to C:\\build.")
    out.mkdir(parents=True, exist_ok=True)
    load_voice(opt("--timeline"))
    reset_scene(tl.frames, tl.fps)
    random.seed(42)
    build(tl)
    fail_if_problems()
    scene = bpy.context.scene
    bpy.ops.wm.save_as_mainfile(filepath=str(out / "scene.blend"))
    if opt("--stills"):
        for f in [int(x) for x in opt("--stills").split(",")]:
            scene.frame_set(f)
            scene.render.filepath = str(out / f"still_{f:04d}.png")
            bpy.ops.render.render(write_still=True)
    if "--anim" in args:
        (out / "frames").mkdir(exist_ok=True)
        scene.render.image_settings.file_format = "PNG"
        scene.render.use_overwrite = False       # resume: skip frames that already exist
        scene.render.filepath = str(out / "frames" / "f_")
        bpy.ops.render.render(animation=True)
