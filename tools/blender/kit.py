def lin(hex_color: str) -> tuple[float, float, float, float]:
    """sRGB hex -> RGBA linear (Blender works in linear)."""
    h = hex_color.lstrip("#")
    out = []
    for i in (0, 2, 4):
        c = int(h[i:i + 2], 16) / 255
        out.append(c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4)
    return (*out, 1.0)


# ---------- timeline ----------

class Timeline:
    """Window of each scene in Blender frames (they start at 1)."""

    def __init__(self, data: dict):
        self.fps = data["fps"]
        self.frames = data["frames"]
        self.scenes = {s["id"]: (s["start"] + 1, s["end"] + 1) for s in data["scenes"]}

    def at(self, scene_id: str, frac: float = 0.0) -> int:
        start, end = self.scenes[scene_id]
        return int(round(start + (end - start) * frac))

    def secs(self, seconds: float) -> int:
        return max(1, int(round(seconds * self.fps)))


# ---------- timing from the voice ----------

VOICE: dict = {}


def load_voice(timeline_path) -> dict:
    """Loads the video's voice.json (build/<slug>/voice.json, next to the timeline's blender/ folder)."""
    global VOICE
    path = Path(timeline_path).resolve().parent.parent / "voice.json"
    VOICE = json.loads(path.read_text(encoding="utf-8")) if path.exists() else {}
    return VOICE


def _plain(word: str) -> str:
    return word.strip("?.,:;!\"'()").lower()


def word_start(sid: str, word: str, nth: int = 0) -> float:
    """Second (within the scene) at which the word starts, from voice.json."""
    words = VOICE.get(sid, {}).get("words", [])
    hits = [w["start"] for w in words if _plain(w["word"]) == _plain(word)]
    if nth >= len(hits):
        raise KeyError(f"scene {sid}: the word '{word}' (occurrence {nth}) is not in the recorded line. "
                       f"Words: {' '.join(w['word'] for w in words)}")
    return hits[nth]


def W(tl: Timeline, sid: str, word: str, nth: int = 0, off: float = 0.0) -> int:
    """Blender frame at which the word starts (+ off seconds). Use it for every camera, light and action key:
    absolute frames written by hand break on every voice re-take (plants-extinct: ~70 keys shifted by hand)."""
    return tl.at(sid) + int(round((word_start(sid, word, nth) + off) * tl.fps))


# ---------- physical checks (they fail the build) ----------

SAFE_RIGHT = 930 / 1080                  # platform buttons strip (brand.py: nothing with x > 930)
CAPTION_BAND = (1220 / 1920, 1360 / 1920)  # video caption (y measured from the top)
_problems: list[str] = []


def problem(message: str) -> None:
    """Records a physical failure. run() raises at the end of the build if there is any
    (a warning print goes unnoticed: the launcher only detects failure by Traceback)."""
    _problems.append(message)


def fail_if_problems() -> None:
    if _problems:
        found = list(_problems)
        _problems.clear()
        raise RuntimeError("Physical check failed:\n" + "\n".join(f"  - {m}" for m in found))


def require_reach(label: str, shoulder, target, max_reach: float = 0.9) -> None:
    """Does the arm reach the target? (~0.75 m on the kit's arm.) The hand in scene 07 of plants-extinct would have needed 3 m and the
    approved camera had to change during modeling."""
    from mathutils import Vector
    dist = (Vector(shoulder) - Vector(target)).length
    if dist > max_reach:
        problem(f"{label}: the shoulder is {dist:.2f} m from the target (reach {max_reach:.2f} m)")


def require_grounded(label: str, obj, scene=None, tol: float = 0.05) -> None:
    """Object resting on the ground: a ray cast down from the object's lowest point must find ground within 'tol'.
    The object and its children are hidden during the ray so it does not hit them."""
    from mathutils import Vector
    scene = scene or bpy.context.scene
    own = [obj, *obj.children_recursive]
    if obj.type == "MESH":
        low_pt = min((obj.matrix_world @ v.co for v in obj.data.vertices), key=lambda c: c.z)
    else:
        low_pt = min((obj.matrix_world @ Vector(c) for c in obj.bound_box), key=lambda c: c.z)
    was = [o.hide_viewport for o in own]
    for o in own:
        o.hide_viewport = True
    try:
        bpy.context.view_layer.update()
        hit, loc, *_ = scene.ray_cast(bpy.context.evaluated_depsgraph_get(),
                                      Vector((low_pt.x, low_pt.y, low_pt.z + tol)), Vector((0, 0, -1)), distance=50.0)
    finally:
        for o, h in zip(own, was):
            o.hide_viewport = h
        bpy.context.view_layer.update()
    if not hit:
        problem(f"{label}: no ground below (x {low_pt.x:.2f}, y {low_pt.y:.2f})")
    elif low_pt.z - loc.z > tol:
        problem(f"{label}: floats {low_pt.z - loc.z:.2f} m above the ground")


def require_in_frame(label: str, scene, cam, point, frame: int, margin: float = 0.03) -> None:
    """Subject inside the 9:16 safe area in the frame: clear of the edge, the right-hand buttons and the caption band."""
    from bpy_extras.object_utils import world_to_camera_view
    from mathutils import Vector
    point = point.matrix_world.translation if hasattr(point, "matrix_world") else Vector(point)
    scene.frame_set(frame)
    co = world_to_camera_view(scene, cam, point)
    x, y = co.x, 1.0 - co.y
    where = f"(x {x:.2f}, y {y:.2f} from the top)"
    if co.z <= 0:
        problem(f"{label} at frame {frame}: behind the camera")
    elif not (margin <= x <= SAFE_RIGHT and margin <= y <= 1 - margin):
        problem(f"{label} at frame {frame}: outside the safe area {where}")
    elif CAPTION_BAND[0] <= y <= CAPTION_BAND[1]:
        problem(f"{label} at frame {frame}: behind the caption {where}")


# ---------- geometry ----------

def mesh_object(name, verts, faces, mats, location=(0, 0, 0), face_mats=None):
    mesh = bpy.data.meshes.new(name)
    mesh.from_pydata(verts, [], faces)
    for m in mats:
        mesh.materials.append(m)
    if face_mats:
        for poly, idx in zip(mesh.polygons, face_mats):
            poly.material_index = idx
    mesh.update()
    obj = bpy.data.objects.new(name, mesh)
    obj.location = location
    bpy.context.collection.objects.link(obj)
    return obj


def _box_geo(sx, sy, sz, ox=0.0, oy=0.0, oz=0.0):
    v = [(ox + x, oy + y, oz + z) for z in (0, sz) for y in (0, sy) for x in (0, sx)]
    f = [(0, 2, 3, 1), (4, 5, 7, 6), (0, 1, 5, 4), (2, 6, 7, 3), (0, 4, 6, 2), (1, 3, 7, 5)]
    return v, f


def _prism_geo(n, r_bottom, r_top, height, oz=0.0, ox=0.0, oy=0.0, sx=1.0, sy=1.0):
    v = []
    for z, r in ((oz, r_bottom), (oz + height, r_top)):
        for i in range(n):
            a = 2 * math.pi * i / n
            v.append((ox + r * sx * math.cos(a), oy + r * sy * math.sin(a), z))
    f = [tuple(range(n - 1, -1, -1)), tuple(range(n, 2 * n))]
    f += [(i, (i + 1) % n, n + (i + 1) % n, n + i) for i in range(n)]
    return v, f


def _gem_geo(r, oz=0.0, stretch=1.15, ox=0.0, oy=0.0):
    v = [(ox, oy, oz - r * stretch), (ox + r, oy, oz), (ox, oy + r, oz), (ox - r, oy, oz),
         (ox, oy - r, oz), (ox, oy, oz + r * stretch)]
    f = [(0, 2, 1), (0, 3, 2), (0, 4, 3), (0, 1, 4), (5, 1, 2), (5, 2, 3), (5, 3, 4), (5, 4, 1)]
    return v, f


def merge(*parts):
    """Merges several geometries (verts, faces) into one; returns verts, faces and the part index per face."""
    verts, faces, owner = [], [], []
    for k, (v, f) in enumerate(parts):
        base = len(verts)
        verts += v
        faces += [tuple(i + base for i in face) for face in f]
        owner += [k] * len(f)
    return verts, faces, owner


def box(name, center, size, mat):
    """Box with its origin at the bottom corner (object coordinates in meters)."""
    sx, sy, sz = size
    v, f = _box_geo(sx, sy, sz)
    cx, cy, cz = center
    return mesh_object(name, v, f, [mat] if mat else [], (cx - sx / 2, cy - sy / 2, cz))


def box_span(name, x0, x1, y0, y1, z0, height, mat):
    return box(name, ((x0 + x1) / 2, (y0 + y1) / 2, z0), (x1 - x0, y1 - y0, height), mat)


def prism(name, base, n, r_bottom, r_top, height, mat):
    v, f = _prism_geo(n, r_bottom, r_top, height)
    return mesh_object(name, v, f, [mat], base)


def gem(name, center, radius, mat, stretch=1.15):
    v, f = _gem_geo(radius, stretch=stretch)
    return mesh_object(name, v, f, [mat], center)


def rect_with_holes(name, x0, x1, y0, y1, z0, height, holes, mat):
    """Rectangular slab with rectangular holes (x0, x1, y0, y1), built from cells."""
    xs = sorted({x0, x1, *[c for h in holes for c in h[:2] if x0 < c < x1]})
    ys = sorted({y0, y1, *[c for h in holes for c in h[2:] if y0 < c < y1]})
    cells = []
    for xa, xb in zip(xs, xs[1:]):
        for ya, yb in zip(ys, ys[1:]):
            cx, cy = (xa + xb) / 2, (ya + yb) / 2
            if any(h[0] < cx < h[1] and h[2] < cy < h[3] for h in holes):
                continue
            cells.append(box_span(f"{name}", xa, xb, ya, yb, z0, height, mat))
    return cells


def skin_mesh(name, joints, edges, radii, subdivide=1, decimate=0.5):
    """Low-poly organic mesh from a skeleton (Skin + Subsurf + Decimate modifiers applied).
    joints: list of (x, y, z); edges: index pairs; radii: radius of each joint. Returns the mesh."""
    mesh = bpy.data.meshes.new(name + "Skel")
    mesh.from_pydata(joints, edges, [])
    obj = bpy.data.objects.new(name + "Skel", mesh)
    bpy.context.collection.objects.link(obj)
    obj.modifiers.new("Skin", "SKIN")
    for i, r in enumerate(radii):
        mesh.skin_vertices[0].data[i].radius = (r, r)
    mesh.skin_vertices[0].data[0].use_root = True
    if subdivide:
        obj.modifiers.new("Subsurf", "SUBSURF").levels = subdivide
    dec = obj.modifiers.new("Decimate", "DECIMATE")
    dec.ratio = decimate
    depsgraph = bpy.context.evaluated_depsgraph_get()
    result = bpy.data.meshes.new_from_object(obj.evaluated_get(depsgraph))
    result.name = name
    for poly in result.polygons:
        poly.use_smooth = False
    bpy.data.objects.remove(obj)
    return result


def with_parts(mesh, *parts):
    """New mesh = existing mesh + extra geometries (e.g. a head), all low-poly and flat."""
    verts = [tuple(v.co) for v in mesh.vertices]
    faces = [tuple(p.vertices) for p in mesh.polygons]
    allv, allf, _ = merge((verts, faces), *parts)
    out = bpy.data.meshes.new(mesh.name + "Full")
    out.from_pydata(allv, [], allf)
    out.update()
    return out


def loft_geo(rings, cap_start=True, cap_end=True):
    """Surface joining closed rings with the same number of points (sections of a body), with caps."""
    n = len(rings[0])
    verts = [tuple(p) for ring in rings for p in ring]
    faces = [(i * n + j, i * n + (j + 1) % n, (i + 1) * n + (j + 1) % n, (i + 1) * n + j)
             for i in range(len(rings) - 1) for j in range(n)]
    if cap_start:
        faces.append(tuple(range(n - 1, -1, -1)))
    if cap_end:
        last = (len(rings) - 1) * n
        faces.append(tuple(range(last, last + n)))
    return verts, faces


def _frame(t):
    """Two unit vectors perpendicular to direction t (to build a ring around it)."""
    ref = (0.0, 0.0, 1.0) if abs(t[2]) < 0.9 else (1.0, 0.0, 0.0)
    u = _cross(t, ref)
    u = _norm(u)
    return u, _cross(t, u)


def _cross(a, b):
    return (a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0])


def _norm(v):
    m = math.sqrt(sum(c * c for c in v)) or 1.0
    return tuple(c / m for c in v)


def tube_geo(points, radii, n=6, squash=1.0, twist=0.0):
    """Low-poly tube along a line of points, with its own radius at each point (legs, neck, tail, branches).
    squash flattens the ring in one direction (ears, muzzle); twist rotates the ring (radians)."""
    rings = []
    for k, (p, r) in enumerate(zip(points, radii)):
        a = points[max(k - 1, 0)]
        b = points[min(k + 1, len(points) - 1)]
        u, v = _frame(_norm(tuple(bb - aa for aa, bb in zip(a, b))))
        ring = []
        for i in range(n):
            ang = twist + 2 * math.pi * i / n
            cu, cv = math.cos(ang) * r, math.sin(ang) * r * squash
            ring.append(tuple(p[c] + cu * u[c] + cv * v[c] for c in range(3)))
        rings.append(ring)
    return loft_geo(rings)


def xform_geo(geo, matrix):
    """Applies a matrix (mathutils.Matrix 4x4) to the vertices of a geometry (verts, faces)."""
    from mathutils import Vector
    verts, faces = geo[0], geo[1]
    return [tuple(matrix @ Vector(v)) for v in verts], faces


def fix_normals(obj):
    """Outward normals (hand-built meshes can come out with flipped faces, and flat lighting inverts)."""
    import bmesh
    bm = bmesh.new()
    bm.from_mesh(obj.data)
    bmesh.ops.recalc_face_normals(bm, faces=bm.faces)
    bm.to_mesh(obj.data)
    bm.free()
    obj.data.update()
    return obj


def _ico_geo(r, center, scale=(1, 1, 1)):
    """Icosphere subdivided once (80 faces), flattened by 'scale'."""
    t = (1 + 5 ** 0.5) / 2
    base = [(-1, t, 0), (1, t, 0), (-1, -t, 0), (1, -t, 0), (0, -1, t), (0, 1, t), (0, -1, -t), (0, 1, -t),
            (t, 0, -1), (t, 0, 1), (-t, 0, -1), (-t, 0, 1)]
    faces = [(0, 11, 5), (0, 5, 1), (0, 1, 7), (0, 7, 10), (0, 10, 11), (1, 5, 9), (5, 11, 4), (11, 10, 2),
             (10, 7, 6), (7, 1, 8), (3, 9, 4), (3, 4, 2), (3, 2, 6), (3, 6, 8), (3, 8, 9), (4, 9, 5), (2, 4, 11),
             (6, 2, 10), (8, 6, 7), (9, 8, 1)]
    verts = [tuple(c / math.sqrt(sum(x * x for x in v)) for c in v) for v in base]
    cache, out_f = {}, []

    def mid(a, b):
        k = tuple(sorted((a, b)))
        if k not in cache:
            m = [(verts[a][i] + verts[b][i]) / 2 for i in range(3)]
            n = math.sqrt(sum(x * x for x in m))
            verts.append(tuple(x / n for x in m))
            cache[k] = len(verts) - 1
        return cache[k]

    for a, b, c in faces:
        ab, bc, ca = mid(a, b), mid(b, c), mid(c, a)
        out_f += [(a, ab, ca), (b, bc, ab), (c, ca, bc), (ab, bc, ca)]
    v = [(center[0] + x * r * scale[0], center[1] + y * r * scale[1], center[2] + z * r * scale[2]) for x, y, z in verts]
    return v, out_f


def water_grid(name, x0, x1, y0, y1, z, mat, cell=0.8, amp=0.06, seed=1):
    """Low-poly water surface: triangle grid with slightly random heights (facets that glint)."""
    rnd = random.Random(seed)
    nx, ny = max(2, int((x1 - x0) / cell)), max(2, int((y1 - y0) / cell))
    verts = [(x0 + (x1 - x0) * i / nx, y0 + (y1 - y0) * j / ny, rnd.uniform(-amp, amp))
             for j in range(ny + 1) for i in range(nx + 1)]
    faces = []
    for j in range(ny):
        for i in range(nx):
            a, b = j * (nx + 1) + i, j * (nx + 1) + i + 1
            c, d = a + nx + 1, b + nx + 1
            faces += [(a, b, d), (a, d, c)] if (i + j) % 2 else [(a, b, c), (b, d, c)]
    return mesh_object(name, verts, faces, [mat], (0, 0, z))


def instance(name, mesh, location, mat=None, rotation=(0, 0, 0)):
    """Object that reuses a mesh (light copy); the material can belong to the object itself."""
    obj = bpy.data.objects.new(name, mesh)
    obj.location = location
    obj.rotation_euler = rotation
    bpy.context.collection.objects.link(obj)
    if mat is not None:
        if not mesh.materials:
            mesh.materials.append(mat)
        obj.material_slots[0].link = "OBJECT"
        obj.material_slots[0].material = mat
    return obj


# ---------- materials ----------

def principled(mat):
    nt = mat.node_tree
    return nt.nodes.get("Principled BSDF") or next(n for n in nt.nodes if n.type == "BSDF_PRINCIPLED")


def flat(name, color, rough=0.9, metallic=0.0, emission=None, strength=0.0):
    mat = bpy.data.materials.new(name)
    if hasattr(mat, "use_nodes") and not mat.use_nodes:
        mat.use_nodes = True
    p = principled(mat)
    p.inputs["Base Color"].default_value = lin(color)
    p.inputs["Roughness"].default_value = rough
    p.inputs["Metallic"].default_value = metallic
    if emission:
        p.inputs["Emission Color"].default_value = lin(emission)
        p.inputs["Emission Strength"].default_value = strength
    return mat


def keyed_emission(name, color, emission, strength):
    """Emissive material; returns (material, emission strength socket to animate)."""
    mat = flat(name, color, emission=emission, strength=strength)
    return mat, principled(mat).inputs["Emission Strength"]


def window_material(name, wall, seed):
    """Facade with a grid of windows, part of them lit in amber.
    Returns (material, brightness Value node, wall color socket)."""
    mat = flat(name, wall)
    nt = mat.node_tree
    n, links = nt.nodes, nt.links
    p = principled(mat)
    rnd = random.Random(seed)

    coord = n.new("ShaderNodeTexCoord")
    sep = n.new("ShaderNodeSeparateXYZ")
    add = n.new("ShaderNodeMath"); add.operation = "ADD"
    comb = n.new("ShaderNodeCombineXYZ")
    offset = n.new("ShaderNodeVectorMath"); offset.operation = "ADD"
    offset.inputs[1].default_value = (rnd.uniform(0, 50), rnd.uniform(0, 50), 0)
    scale = n.new("ShaderNodeVectorMath"); scale.operation = "SCALE"
    scale.inputs["Scale"].default_value = 0.1
    brick = n.new("ShaderNodeTexBrick")
    brick.offset = 0.0
    brick.inputs["Color1"].default_value = (0, 0, 0, 1)
    brick.inputs["Color2"].default_value = (1, 1, 1, 1)
    brick.inputs["Scale"].default_value = 1.0
    brick.inputs["Mortar Size"].default_value = 0.1
    brick.inputs["Mortar Smooth"].default_value = 0.0
    brick.inputs["Brick Width"].default_value = 0.28
    brick.inputs["Row Height"].default_value = 0.34

    # Height of the block inside the building (the object's "win_z" property): windows stay
    # aligned between stacked blocks and follow the block when it falls.
    win_z = n.new("ShaderNodeAttribute")
    win_z.attribute_type = "OBJECT"
    win_z.attribute_name = "win_z"
    z_total = n.new("ShaderNodeMath"); z_total.operation = "ADD"
    links.new(coord.outputs["Object"], sep.inputs[0])
    links.new(sep.outputs["X"], add.inputs[0])
    links.new(sep.outputs["Y"], add.inputs[1])
    links.new(add.outputs[0], comb.inputs["X"])
    links.new(sep.outputs["Z"], z_total.inputs[0])
    links.new(win_z.outputs["Fac"], z_total.inputs[1])
    links.new(z_total.outputs[0], comb.inputs["Y"])
    links.new(comb.outputs[0], offset.inputs[0])
    links.new(offset.outputs[0], scale.inputs[0])
    links.new(scale.outputs[0], brick.inputs["Vector"])

    window = n.new("ShaderNodeMath"); window.operation = "SUBTRACT"
    window.inputs[0].default_value = 1.0
    links.new(brick.outputs["Fac"], window.inputs[1])            # 1 = window, 0 = wall
    bw = n.new("ShaderNodeRGBToBW")
    links.new(brick.outputs["Color"], bw.inputs[0])
    lit_pick = n.new("ShaderNodeMath"); lit_pick.operation = "GREATER_THAN"
    lit_pick.inputs[1].default_value = rnd.uniform(0.35, 0.6)    # fraction of lit windows
    links.new(bw.outputs[0], lit_pick.inputs[0])
    lit = n.new("ShaderNodeMath"); lit.operation = "MULTIPLY"
    links.new(window.outputs[0], lit.inputs[0])
    links.new(lit_pick.outputs[0], lit.inputs[1])

    base = n.new("ShaderNodeMix"); base.data_type = "RGBA"
    base.inputs["A"].default_value = lin(wall)
    base.inputs["B"].default_value = lin(GLASS)
    glass = n.new("ShaderNodeValue")
    glass.outputs[0].default_value = 1.0
    glass_amount = n.new("ShaderNodeMath"); glass_amount.operation = "MULTIPLY"
    links.new(window.outputs[0], glass_amount.inputs[0])
    links.new(glass.outputs[0], glass_amount.inputs[1])
    links.new(glass_amount.outputs[0], base.inputs["Factor"])
    links.new(base.outputs["Result"], p.inputs["Base Color"])

    power = n.new("ShaderNodeValue")
    power.outputs[0].default_value = 2.2
    strength = n.new("ShaderNodeMath"); strength.operation = "MULTIPLY"
    links.new(lit.outputs[0], strength.inputs[0])
    links.new(power.outputs[0], strength.inputs[1])
    p.inputs["Emission Color"].default_value = lin(WARM if rnd.random() < 0.5 else LUZ)
    links.new(strength.outputs[0], p.inputs["Emission Strength"])
    return mat, power, base.inputs["A"], glass


# ---------- animation ----------

def key(owner, attr, value, frame):
    setattr(owner, attr, value)
    owner.keyframe_insert(attr, frame=frame)


def ramp(owner, attr, start_value, end_value, f0, f1):
    """Holds start_value until f0 and eases to end_value at f1."""
    key(owner, attr, start_value, f0)
    key(owner, attr, end_value, max(f1, f0 + 1))


def switch_off(owner, attr, on_value, frame, flicker=False):
    """Lit from frame 1 until 'frame'; with flicker, it blinks before going out."""
    key(owner, attr, on_value, 1)
    if flicker:
        key(owner, attr, on_value, frame - 6)
        key(owner, attr, on_value * 0.1, frame - 5)
        key(owner, attr, on_value, frame - 3)
    key(owner, attr, on_value, frame - 1)
    key(owner, attr, 0.0, frame)


def grow(obj, f0, f1, target=1.0, start=0.0):
    """Scale from 'start' to 'target' (object invisible before that, if start = 0)."""
    s0 = (start, start, start)
    t = target if isinstance(target, tuple) else (target, target, target)
    key(obj, "scale", s0, 1)
    ramp(obj, "scale", s0, t, f0, f1)


def vanish(obj, f0, f1):
    """Disappears between f0 and f1. If the object already has animation (e.g. it grew earlier), frame 1 is left alone."""
    current = tuple(obj.scale)
    if obj.animation_data is None:
        key(obj, "scale", current, 1)
    ramp(obj, "scale", current, (0.0, 0.0, 0.0), f0, f1)


def color_ramp_socket(socket, hex_from, hex_to, f0, f1):
    key(socket, "default_value", lin(hex_from), 1)
    ramp(socket, "default_value", lin(hex_from), lin(hex_to), f0, f1)


